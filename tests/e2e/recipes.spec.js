import { test, expect } from '@playwright/test';
import { enter, assertFits } from './helpers.js';
test('create and inspect a recipe then assign and remove it from the weekly menu', async ({ page }) => {
  await enter(page, 'recetas');
  await page.getByRole('button', { name: 'Nueva receta' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Título', { exact: true }).fill('Sopa de prueba');
  await dialog.getByLabel('Ingredientes (uno por línea)').fill('Agua\nSal\nVerduras');
  await dialog.getByLabel('Instrucciones').fill('Hervir las verduras.\nServir caliente.');
  await dialog.getByLabel('URL de información (opcional)').fill('https://example.com/receta');
  await dialog.getByRole('button', { name: 'Guardar receta' }).click();
  await page.getByRole('button', { name: 'Ver receta: Sopa de prueba' }).click();
  await expect(dialog.getByText('Verduras', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Hervir las verduras.', { exact: false })).toBeVisible();
  await expect(dialog.getByRole('link', { name: 'Ver enlace de la receta' })).toHaveAttribute('href', 'https://example.com/receta');
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('tab', { name: 'Menú semanal' }).click();
  const lunch = page.getByLabel(/^Comida del /).first();
  await lunch.selectOption({ label: 'Sopa de prueba' });
  const dinner = page.getByLabel(/^Cena del /).first();
  await dinner.selectOption({ label: 'Sopa de prueba' });
  await page.reload();
  await page.getByRole('tab', { name: 'Menú semanal' }).click();
  await expect(page.getByLabel(/^Comida del /).first().locator('option:checked')).toHaveText('Sopa de prueba');
  await expect(page.getByLabel(/^Cena del /).first().locator('option:checked')).toHaveText('Sopa de prueba');
  await page.getByRole('button', { name: 'Semana siguiente' }).click();
  await expect(page.getByLabel(/^Comida del /).first()).toHaveValue('');
  await page.getByRole('button', { name: 'Semana anterior' }).click();
  await page.getByLabel(/^Comida del /).first().selectOption('');
  await expect(page.getByLabel(/^Comida del /).first()).toHaveValue('');
  await assertFits(page);
});
test('recipe list and weekly menu handle no recipes', async ({ page }) => {
  await enter(page, 'recetas');
  await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('marsito.demo.v1')); s.recipes = []; s.menu = {}; localStorage.setItem('marsito.demo.v1', JSON.stringify(s)); });
  await page.reload();
  await expect(page.getByText('Aquí empieza vuestro recetario')).toBeVisible();
  await page.getByRole('tab', { name: 'Menú semanal' }).click();
  await expect(page.getByLabel(/^Comida del /).first()).toBeDisabled();
  await expect(page.getByText('Crea una receta para empezar a planificar.')).toBeVisible();
});
