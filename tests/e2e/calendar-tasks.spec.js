import { test, expect } from '@playwright/test';
import { enter, assertFits } from './helpers.js';
test('create an event, respond and comment as both profiles', async ({ page }) => {
  await enter(page, 'calendario');
  await page.getByRole('button', { name: 'Nuevo evento' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Crear evento' }).click();
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Título', { exact: true }).fill('Cena de prueba');
  await dialog.getByLabel('Fecha', { exact: true }).fill('2026-08-15');
  await dialog.getByLabel('Hora', { exact: true }).fill('20:30');
  await dialog.getByLabel('Descripción', { exact: true }).fill('En la terraza');
  await dialog.getByLabel('URL de información (opcional)').fill('https://example.com/plan');
  await dialog.getByRole('button', { name: 'Crear evento' }).click();
  await page.getByRole('button', { name: 'Ver evento: Cena de prueba' }).click();
  await expect(dialog.getByRole('link', { name: 'Más información' })).toHaveAttribute('href', 'https://example.com/plan');
  await dialog.getByRole('button', { name: 'Sí, voy' }).click();
  await expect(dialog.getByText('Álex · Sí')).toBeVisible();
  await dialog.getByLabel('Tu comentario').fill('Llevo pan');
  await dialog.getByRole('button', { name: 'Comentar', exact: true }).click();
  await expect(dialog.getByText('Llevo pan')).toBeVisible();
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByLabel('Perfil activo').selectOption('sam');
  await page.getByRole('button', { name: 'Ver evento: Cena de prueba' }).click();
  await dialog.getByRole('button', { name: 'No puedo' }).click();
  await expect(dialog.getByText('Sam · No')).toBeVisible();
  await dialog.getByLabel('Tu comentario').fill('Llego después');
  await dialog.getByRole('button', { name: 'Comentar', exact: true }).click();
  await expect(dialog.getByText('Llego después')).toBeVisible();
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Mes siguiente' }).click();
  await page.getByRole('button', { name: 'Mes anterior' }).click();
  await assertFits(page);
});
test('tasks are shared, completable, persistent and user input stays literal', async ({ page }) => {
  await enter(page, 'tareas');
  await page.getByRole('button', { name: 'Nueva tarea' }).click();
  const dialog = page.getByRole('dialog');
  const title = '<img src=x onerror=window.attacked=true>';
  await dialog.getByLabel('Título', { exact: true }).fill(title);
  await dialog.getByLabel('Tarea', { exact: true }).fill('Una tarea segura');
  await dialog.getByRole('button', { name: 'Crear tarea' }).click();
  await page.getByLabel('Perfil activo').selectOption('sam');
  await page.getByRole('checkbox', { name: title, exact: true }).check();
  await page.reload();
  await expect(page.getByRole('checkbox', { name: title, exact: true })).toBeChecked();
  expect(await page.evaluate(() => window.attacked)).toBeUndefined();
  await assertFits(page);
});
test('event links reject unsafe protocols and comments never execute markup', async ({ page }) => {
  await enter(page, 'calendario');
  await page.getByRole('button', { name: 'Nuevo evento' }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Título', { exact: true }).fill('Evento seguro');
  await dialog.getByLabel('Hora', { exact: true }).fill('10:00');
  await dialog.getByLabel('Descripción', { exact: true }).fill('Hola');
  await dialog.getByLabel('URL de información (opcional)').fill('javascript:alert(1)');
  await dialog.getByRole('button', { name: 'Crear evento' }).click();
  await expect(dialog.getByRole('alert')).toContainText('URL');
  await dialog.getByLabel('URL de información (opcional)').fill('');
  await dialog.getByRole('button', { name: 'Crear evento' }).click();
  await page.getByRole('button', { name: 'Ver evento: Evento seguro' }).click();
  const text = '<img src=x onerror=window.attacked=true>';
  await dialog.getByLabel('Tu comentario').fill(text);
  await dialog.getByRole('button', { name: 'Comentar', exact: true }).click();
  await expect(dialog.getByText(text, { exact: true })).toBeVisible();
  expect(await page.evaluate(() => window.attacked)).toBeUndefined();
});
test('empty calendar and tasks explain their state', async ({ page }) => {
  await enter(page, 'calendario');
  await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('marsito.demo.v1')); s.events = []; s.tasks = []; localStorage.setItem('marsito.demo.v1', JSON.stringify(s)); });
  await page.reload();
  await expect(page.getByText('Un día por llenar')).toBeVisible();
  await page.getByRole('navigation').getByRole('link', { name: 'Tareas', exact: true }).click();
  await expect(page.getByText('Todo al día')).toBeVisible();
});
