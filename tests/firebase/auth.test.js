import test, { before, beforeEach, after } from 'node:test';
import assert from 'node:assert/strict';
import { doc, updateDoc, onSnapshot } from 'firebase/firestore';
import { testEnvironment } from './helpers.js';
import { seedSpace } from './provision-fixture.js';
import { makeUser, until, emulatorConfig } from './auth-helpers.js';
import { initializeFirebase } from '../../src/firebase/client.js';
import { deleteApp } from 'firebase/app';
import { applyActionCode, confirmPasswordReset, signInWithEmailAndPassword } from 'firebase/auth';
import { createFirebaseStore } from '../../src/data/firebase-store.js';
let env;
before(async () => { env = await testEnvironment(); });
beforeEach(() => env.clearFirestore());
after(() => env?.cleanup());
function storeFor(t, client) { const store = createFirebaseStore({ ...client, spaceId: 'marsito', online: () => true }); t.after(() => store.destroy()); return store; }
test('an unverified account is separate from a verified but unapproved account', async t => {
  const unverified = storeFor(t, await makeUser(t, 'unverified', false));
  await until(() => unverified.getState().authStatus === 'unverified');
  assert.equal(unverified.getState().tasks.length, 0);
  await unverified.dispatch('auth/resend-verification');
  const approvedEmailOnly = storeFor(t, await makeUser(t, 'outsider'));
  await until(() => approvedEmailOnly.getState().authStatus === 'pending');
  assert.equal(approvedEmailOnly.getState().profiles.length, 0);
  await approvedEmailOnly.dispatch('auth/reset-password', { email: approvedEmailOnly.getState().user.email });
});
test('registration, verification link and password recovery run through the Auth emulator', async t => {
  const client = initializeFirebase(emulatorConfig(crypto.randomUUID()));
  t.after(() => deleteApp(client.auth.app));
  const store = storeFor(t, client);
  const email = `register-${crypto.randomUUID()}@example.test`;
  await until(() => store.getState().authStatus === 'signed-out');
  await store.dispatch('auth/register', { email, password: 'Initial-Password-123!' });
  await until(() => store.getState().authStatus === 'unverified');
  let codes = await (await fetch('http://127.0.0.1:9099/emulator/v1/projects/demo-marsito-beta/oobCodes')).json();
  const verification = codes.oobCodes.find(code => code.email === email && code.requestType === 'VERIFY_EMAIL');
  assert.ok(verification);
  await applyActionCode(client.auth, verification.oobCode);
  await store.dispatch('auth/refresh');
  await until(() => store.getState().authStatus === 'pending');
  await store.dispatch('auth/reset-password', { email });
  codes = await (await fetch('http://127.0.0.1:9099/emulator/v1/projects/demo-marsito-beta/oobCodes')).json();
  const reset = codes.oobCodes.find(code => code.email === email && code.requestType === 'PASSWORD_RESET');
  assert.ok(reset);
  await confirmPasswordReset(client.auth, reset.oobCode, 'Replacement-Password-456!');
  await store.dispatch('logout');
  await signInWithEmailAndPassword(client.auth, email, 'Replacement-Password-456!');
  await until(() => store.getState().authStatus === 'pending');
});
test('both approved users can load data, logout and revocation erase the private snapshot', async t => {
  const a = await makeUser(t, 'alice'), b = await makeUser(t, 'bob');
  await seedSpace(env, { uidA: a.uid, uidB: b.uid });
  const alice = storeFor(t, a), bob = storeFor(t, b);
  await until(() => alice.getState().authStatus === 'ready' && bob.getState().authStatus === 'ready' && bob.getState().tasks.length === 1);
  assert.equal(alice.getState().activeProfileId, a.uid);
  assert.equal(bob.getState().tasks[0].title, 'Plan privado');
  const snapshot = bob.getState(); snapshot.tasks.length = 0; assert.equal(bob.getState().tasks.length, 1);
  await alice.dispatch('logout');
  assert.equal(alice.getState().tasks.length, 0); assert.equal(alice.getState().profiles.length, 0);
  await env.withSecurityRulesDisabled(ctx => updateDoc(doc(ctx.firestore(), 'betaMembers', b.uid), { enabled: false }));
  await until(() => bob.getState().authStatus === 'pending');
  assert.equal(bob.getState().tasks.length, 0); assert.equal(bob.getState().activeProfileId, null);
  await new Promise(resolve => setTimeout(resolve, 100));
  assert.equal(bob.getState().tasks.length, 0);
});
test('a delayed authorized snapshot cannot restore access after membership revocation', async t => {
  const a = await makeUser(t, 'delayed'), b = await makeUser(t, 'partner');
  await seedSpace(env, { uidA: a.uid, uidB: b.uid });
  const delayed = [];
  const listen = (reference, ...args) => {
    if (reference.path !== 'spaces/marsito') return onSnapshot(reference, ...args);
    const [options, callback, onError] = args;
    return onSnapshot(reference, options, snapshot => {
      if (snapshot.metadata.fromCache) callback(snapshot);
      else delayed.push(() => callback(snapshot));
    }, onError);
  };
  const store = createFirebaseStore({ ...a, spaceId: 'marsito', online: () => true, listen });
  t.after(() => store.destroy());
  await until(() => delayed.length > 0);
  await env.withSecurityRulesDisabled(ctx => updateDoc(doc(ctx.firestore(), 'betaMembers', a.uid), { enabled: false }));
  await until(() => store.getState().authStatus === 'pending');
  let restored = false;
  const off = store.subscribe(() => { if (store.getState().authStatus === 'ready') restored = true; });
  delayed.splice(0).forEach(callback => callback());
  await new Promise(resolve => setTimeout(resolve, 100)); off();
  assert.equal(restored, false, 'An old snapshot must not briefly restore ready/private state');
  assert.equal(store.getState().profiles.length, 0);
});
test('wrong credentials never fall back to demo and errors do not echo the password', async t => {
  const client = await makeUser(t, 'wrong'); const store = storeFor(t, client);
  await store.dispatch('logout');
  await assert.rejects(store.dispatch('auth/login', { email: client.email, password: 'NotThePassword-secret' }), error => !error.message.includes('NotThePassword-secret'));
  assert.equal(store.getState().mode, 'firebase');
  assert.equal(store.getState().activeProfileId, null);
  await assert.rejects(store.dispatch('login', { profileId: 'alice' }));
});
